CREATE TABLE permit_businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_dataset TEXT NOT NULL,
    management_number TEXT NOT NULL,
    municipality_code TEXT NOT NULL,
    name TEXT NOT NULL,
    lot_address TEXT,
    road_address TEXT,
    business_type TEXT,
    permitted_at DATE NOT NULL,
    closed_at DATE,
    status_code TEXT,
    detail_status_code TEXT,
    source_x NUMERIC(38, 20),
    source_y NUMERIC(38, 20),
    source_crs INTEGER NOT NULL,
    source_json TEXT NOT NULL,
    issues_json TEXT NOT NULL,
    last_imported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT permit_businesses_pkey PRIMARY KEY (id),
    CONSTRAINT uk_permit_business_source UNIQUE (source_dataset, management_number),
    CONSTRAINT ck_permit_business_dates CHECK (closed_at IS NULL OR closed_at >= permitted_at),
    CONSTRAINT ck_permit_business_coordinates CHECK (
        (source_x IS NULL AND source_y IS NULL) OR
        (source_x IS NOT NULL AND source_y IS NOT NULL)
    )
);
