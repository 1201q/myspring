CREATE TABLE permit_category (
    service_id VARCHAR(100) PRIMARY KEY,
    name TEXT NOT NULL,
    source_group TEXT,
    close_date_supported BOOLEAN NOT NULL
);

CREATE TABLE permit_import_run (
    id VARCHAR(36) PRIMARY KEY,
    category_id VARCHAR(100) NOT NULL REFERENCES permit_category(service_id),
    source_sha256 VARCHAR(64) NOT NULL,
    contract_hash VARCHAR(64) NOT NULL,
    source_file TEXT NOT NULL,
    source_as_of DATE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(20) NOT NULL,
    processed_rows BIGINT NOT NULL DEFAULT 0,
    inserted_count BIGINT NOT NULL DEFAULT 0,
    updated_count BIGINT NOT NULL DEFAULT 0,
    unchanged_count BIGINT NOT NULL DEFAULT 0,
    error_summary TEXT
);

-- A committed owner survives a crashed CLI; only that explicit run may resume it.
CREATE TABLE permit_import_lock (id INTEGER PRIMARY KEY, owner_run VARCHAR(36));
INSERT INTO permit_import_lock(id, owner_run) VALUES (1, NULL);

CREATE TABLE national_permit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id VARCHAR(100) NOT NULL REFERENCES permit_category(service_id),
    municipality_code VARCHAR(50) NOT NULL,
    management_number VARCHAR(255) NOT NULL,
    created_run_id VARCHAR(36) NOT NULL REFERENCES permit_import_run(id),
    last_seen_run_id VARCHAR(36) NOT NULL REFERENCES permit_import_run(id),
    current_version_id BIGINT,
    CONSTRAINT uk_national_permit_identity UNIQUE(category_id, municipality_code, management_number)
);

CREATE TABLE national_permit_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permit_id BIGINT NOT NULL REFERENCES national_permit(id),
    run_id VARCHAR(36) NOT NULL REFERENCES permit_import_run(id),
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    source_as_of DATE NOT NULL,
    name TEXT NOT NULL, lot_address TEXT, road_address TEXT, business_type TEXT,
    permitted_on DATE, closed_on DATE,
    raw_status_code TEXT, raw_status_name TEXT,
    raw_detail_status_code TEXT, raw_detail_status_name TEXT,
    source_x NUMERIC(38,20), source_y NUMERIC(38,20), source_crs INTEGER,
    raw_json TEXT NOT NULL, issues_json TEXT NOT NULL, content_hash VARCHAR(64) NOT NULL,
    CONSTRAINT ck_national_version_dates CHECK(closed_on IS NULL OR permitted_on IS NULL OR closed_on >= permitted_on),
    CONSTRAINT ck_national_version_xy CHECK((source_x IS NULL) = (source_y IS NULL))
);
ALTER TABLE national_permit ADD CONSTRAINT fk_national_current_version
    FOREIGN KEY (current_version_id) REFERENCES national_permit_version(id);
CREATE INDEX ix_national_version_permit ON national_permit_version(permit_id, id);
CREATE INDEX ix_national_version_run ON national_permit_version(run_id);

-- Only events whose version matches national_permit.current_version_id are current.
CREATE TABLE permit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permit_id BIGINT NOT NULL REFERENCES national_permit(id),
    version_id BIGINT NOT NULL REFERENCES national_permit_version(id),
    event_type VARCHAR(10) NOT NULL CHECK(event_type IN ('OPEN','CLOSE')),
    event_date DATE NOT NULL,
    date_basis VARCHAR(30) NOT NULL,
    location_basis VARCHAR(30) NOT NULL DEFAULT 'LATEST_KNOWN_SOURCE',
    CONSTRAINT uk_permit_event_version UNIQUE(version_id, event_type)
);
CREATE INDEX ix_permit_event_date ON permit_event(event_date, event_type);
CREATE INDEX ix_permit_event_permit ON permit_event(permit_id, version_id);

CREATE TABLE permit_import_stage (
    run_id VARCHAR(36) NOT NULL REFERENCES permit_import_run(id),
    row_no BIGINT NOT NULL,
    municipality_code VARCHAR(50) NOT NULL, management_number VARCHAR(255) NOT NULL,
    name TEXT NOT NULL, lot_address TEXT, road_address TEXT, business_type TEXT,
    permitted_on DATE, closed_on DATE,
    raw_status_code TEXT, raw_status_name TEXT,
    raw_detail_status_code TEXT, raw_detail_status_name TEXT,
    source_x NUMERIC(38,20), source_y NUMERIC(38,20), source_crs INTEGER,
    raw_json TEXT NOT NULL, issues_json TEXT NOT NULL, content_hash VARCHAR(64) NOT NULL,
    PRIMARY KEY(run_id, row_no),
    CONSTRAINT uk_permit_stage_identity UNIQUE(run_id, municipality_code, management_number)
);
