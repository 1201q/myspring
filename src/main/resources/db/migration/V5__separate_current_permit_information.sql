-- Additive migration: legacy tables and source staging are deliberately retained.
CREATE TABLE national_permit_current (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id VARCHAR(100) NOT NULL,
    municipality_code VARCHAR(50) NOT NULL,
    management_number VARCHAR(255) NOT NULL,
    created_run_id VARCHAR(36) NOT NULL,
    last_seen_run_id VARCHAR(36) NOT NULL,
    run_id VARCHAR(36) NOT NULL,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    source_as_of DATE NOT NULL,
    name TEXT NOT NULL, lot_address TEXT, road_address TEXT, business_type TEXT,
    permitted_on DATE, closed_on DATE,
    raw_status_code TEXT, raw_status_name TEXT,
    raw_detail_status_code TEXT, raw_detail_status_name TEXT,
    source_x NUMERIC(38,20), source_y NUMERIC(38,20), source_crs INTEGER,
    raw_json TEXT NOT NULL, issues_json TEXT NOT NULL, content_hash VARCHAR(64) NOT NULL,
    UNIQUE(category_id,municipality_code,management_number),
    CHECK(closed_on IS NULL OR permitted_on IS NULL OR closed_on>=permitted_on),
    CHECK((source_x IS NULL)=(source_y IS NULL))
);
-- Historical snapshots only: first load is stored once, in current.
CREATE TABLE national_permit_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permit_id BIGINT NOT NULL,
    run_id VARCHAR(36) NOT NULL,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    source_as_of DATE NOT NULL,
    name TEXT NOT NULL, lot_address TEXT, road_address TEXT, business_type TEXT,
    permitted_on DATE, closed_on DATE,
    raw_status_code TEXT, raw_status_name TEXT,
    raw_detail_status_code TEXT, raw_detail_status_name TEXT,
    source_x NUMERIC(38,20), source_y NUMERIC(38,20), source_crs INTEGER,
    raw_json TEXT NOT NULL, issues_json TEXT NOT NULL, content_hash VARCHAR(64) NOT NULL
);
CREATE INDEX ix_national_history_permit ON national_permit_history(permit_id,id);
CREATE INDEX ix_national_current_open ON national_permit_current(permitted_on,category_id);
CREATE INDEX ix_national_current_close ON national_permit_current(closed_on,category_id);
CREATE TABLE national_current_migration (
    id INTEGER PRIMARY KEY CHECK(id=1),
    current_checkpoint BIGINT NOT NULL DEFAULT 0,
    history_checkpoint BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL
);
