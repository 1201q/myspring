-- Current date corrections automatically replace the visible event dates.
CREATE VIEW national_permit_current_event AS
SELECT id AS permit_id,category_id,'OPEN' AS event_type,permitted_on AS event_date,
       'SOURCE_PERMIT_DATE' AS date_basis FROM national_permit_current WHERE permitted_on IS NOT NULL
UNION ALL
SELECT id,category_id,'CLOSE',closed_on,'SOURCE_CLOSE_DATE'
FROM national_permit_current WHERE closed_on IS NOT NULL;
